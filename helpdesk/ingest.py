import json
import os

# Point directly to your teammate's generated chunks output file
CHUNKS_FILE_PATH = os.path.join("rhd_ingestion", "output", "final_chunks.json")

def load_ingested_chunks():
    """
    Loads pre-processed text chunks generated by the rhd_ingestion module.
    """
    if not os.path.exists(CHUNKS_FILE_PATH):
        # Fallback path check if filename differs
        alt_path = os.path.join("rhd_ingestion", "output", "chunks.json")
        if os.path.exists(alt_path):
            path_to_use = alt_path
        else:
            raise FileNotFoundError(
                f"Ingestion chunks file not found at {CHUNKS_FILE_PATH}. "
                "Ensure your teammate's pipeline has been run first."
            )
    else:
        path_to_use = CHUNKS_FILE_PATH

    with open(path_to_use, "r", encoding="utf-8") as f:
        chunks_data = json.load(f)
        
    return chunks_data

if __name__ == "__main__":
    try:
        data = load_ingested_chunks()
        print(f"Successfully loaded {len(data)} chunks from rhd_ingestion module.")
    except Exception as e:
        print(f"Error loading ingestion chunks: {e}")